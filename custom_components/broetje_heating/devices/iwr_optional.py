def build_optional_iwr_maps() -> tuple[
    dict[str, Any], dict[str, Any], dict[str, dict[int, str]]
]:
    """Build register, sensor, and enum maps for documented optional modules."""
    registers: dict[str, Any] = {}
    sensors: dict[str, Any] = {}
    enum_maps: dict[str, dict[int, str]] = {}
    for spec in OPTIONAL_IWR_SENSOR_SPECS:
        key = spec["key"]
        registers[key] = {
            "address": spec["address"],
            "type": REG_HOLDING,
            "count": spec["count"],
            "data_type": spec["data_type"],
            "scale": spec["scale"],
            "source_access": spec["source_access"],
            "source_format": spec["source_format"],
            "sub_device": spec["sub_device"],
        }
        sensor: dict[str, Any] = {
            "register": key,
            "translation_key": key,
            "device_class": spec["device_class"],
            "unit": spec["unit"],
            "state_class": "measurement",
            "sub_device": spec["sub_device"],
        }
        if spec["enum"]:
            enum_key = f"iwr_optional_{key}"
            sensor["enum_map"] = enum_key
            enum_maps[enum_key] = spec["enum"]
        sensors[key] = sensor
    return registers, sensors, enum_maps
